import AppKit
import Observation
import os

@Observable
final class ClipboardMonitor {
    /// History in most-recently-used order. Pinned items live here too; use
    /// `displayHistory` for the order shown in the panel.
    var items: [ClipboardItem] = []
    var snippets: [ClipboardItem] = []

    /// Recording is paused until this date (`.distantFuture` = until resumed).
    private(set) var pausedUntil: Date?
    /// Skip exactly the next clipboard change.
    private(set) var isSkippingNextCopy = false

    var isPaused: Bool { pausedUntil != nil || isSkippingNextCopy }

    private var timer: Timer?
    private var lastChangeCount: Int = 0
    private let store = JSONFileStore<ClipboardItem>(fileName: "clipboard_history.json", label: "clipboard history")
    private let snippetStore = JSONFileStore<ClipboardItem>(fileName: "snippets.json", label: "snippets")
    private let imageProcessingQueue = DispatchQueue(label: "com.clippy.imageprocessing", qos: .utility)
    private let logger = Logger(subsystem: "com.clippy", category: "ClipboardMonitor")
    private var ignoreNextChange = false
    private var lastPurgeCheck: Date = .distantPast
    private var lastClipboardChangeTime: Date = .distantPast

    /// Text larger than this is not recorded; it would bloat the history file.
    static let maxTextBytes = 1_000_000
    /// Rich-text representations larger than this are dropped (plain text is kept).
    static let maxRichTextBytes = 2_000_000

    private static let sensitiveTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("com.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    private static let imageTypes: Set<NSPasteboard.PasteboardType> = [.tiff, .png]
    private static let textTypes: Set<NSPasteboard.PasteboardType> = [.string, .rtf, .html]

    init() {
        items = store.load()
        snippets = snippetStore.load()
        lastChangeCount = NSPasteboard.general.changeCount
    }

    func start() {
        purgeExpiredItems()
        reconcileImageFiles()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.checkClipboard()
        }
    }

    /// At launch: delete image files no longer referenced by any item, then
    /// re-save so legacy inline-image migrations are recorded and any
    /// pre-existing plaintext sensitive entries are re-encrypted at rest.
    private func reconcileImageFiles() {
        var referenced = Set<String>()
        for item in items + snippets where item.contentType == .image {
            if let name = item.imageFileName { referenced.insert(name) }
        }
        ImageStore.shared.pruneUnreferenced(keeping: referenced)

        if !items.isEmpty { store.save(items) }
        if !snippets.isEmpty { snippetStore.save(snippets) }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        store.saveImmediately(items)
        snippetStore.saveImmediately(snippets)
    }

    // MARK: - Queries

    /// Pinned items first (most recently used first), then the rest.
    var displayHistory: [ClipboardItem] {
        items.filter(\.isPinned) + items.filter { !$0.isPinned }
    }

    func filteredItems(_ query: SearchQuery) -> [ClipboardItem] {
        let history = displayHistory
        guard !query.isEmpty else { return history }
        return history.filter(query.matches)
    }

    func filteredSnippets(_ query: SearchQuery) -> [ClipboardItem] {
        guard !query.isEmpty else { return snippets }
        return snippets.filter(query.matches)
    }

    // MARK: - History editing

    func deleteItem(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        deleteImageFile(for: item)
        store.save(items)
    }

    /// Clears all unpinned history.
    func clearAll() {
        removeItems { !$0.isPinned }
    }

    /// Clears unpinned items copied or used within the last `minutes`.
    func clearItems(inLastMinutes minutes: Int) {
        let cutoff = Date().addingTimeInterval(-TimeInterval(minutes * 60))
        removeItems { !$0.isPinned && $0.timestamp >= cutoff }
    }

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
        store.save(items)
    }

    /// Moves a history item to the top, e.g. after it was pasted from the panel.
    func markUsed(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        moveToFront(at: index)
        store.save(items)
    }

    func setIgnoreNextChange() {
        ignoreNextChange = true
    }

    // MARK: - Pause

    func pause(for duration: TimeInterval?) {
        isSkippingNextCopy = false
        pausedUntil = duration.map { Date().addingTimeInterval($0) } ?? .distantFuture
    }

    func skipNextCopy() {
        pausedUntil = nil
        isSkippingNextCopy = true
    }

    func resume() {
        pausedUntil = nil
        isSkippingNextCopy = false
    }

    // MARK: - Snippets

    /// Saves a copy of `item` as a snippet. Returns false if an identical
    /// snippet already exists.
    @discardableResult
    func saveAsSnippet(_ item: ClipboardItem) -> Bool {
        if snippets.contains(where: { $0.hasSameContent(as: item) }) {
            return false
        }
        var toSave = item
        toSave.isPinned = false
        // Give image snippets their own copy of the file so purging history
        // does not delete a file the snippet still references.
        if item.contentType == .image,
           let name = item.imageFileName,
           let copied = ImageStore.shared.copy(name) {
            toSave = ClipboardItem.image(fileName: copied, hash: item.imageHash, sourceAppName: item.sourceAppName, sourceAppBundleID: item.sourceAppBundleID)
        }
        snippets.insert(toSave, at: 0)
        snippetStore.save(snippets)
        return true
    }

    func deleteSnippet(_ item: ClipboardItem) {
        snippets.removeAll { $0.id == item.id }
        deleteImageFile(for: item)
        snippetStore.save(snippets)
    }

    /// Updates a snippet's title and, for text snippets, its content.
    func updateSnippet(_ item: ClipboardItem, title: String, text: String?) {
        guard let index = snippets.firstIndex(where: { $0.id == item.id }) else { return }
        let trimmedTitle = title.trimmingCharacters(in: .whitespacesAndNewlines)
        snippets[index].title = trimmedTitle.isEmpty ? nil : trimmedTitle
        if let text, snippets[index].contentType == .text, text != snippets[index].textContent {
            snippets[index].textContent = text
            // Formatting no longer matches the edited text.
            snippets[index].rtfData = nil
            snippets[index].htmlData = nil
        }
        snippetStore.save(snippets)
    }

    /// Moves a snippet up (negative offset) or down. Returns its new index.
    @discardableResult
    func moveSnippet(_ item: ClipboardItem, by offset: Int) -> Int? {
        guard let index = snippets.firstIndex(where: { $0.id == item.id }) else { return nil }
        let target = min(max(index + offset, 0), snippets.count - 1)
        guard target != index else { return index }
        let snippet = snippets.remove(at: index)
        snippets.insert(snippet, at: target)
        snippetStore.save(snippets)
        return target
    }

    struct SnippetExport: Codable {
        var title: String?
        var text: String
    }

    /// JSON export of all text snippets (images are not exported).
    func exportSnippets() throws -> Data {
        let exported = snippets.compactMap { snippet -> SnippetExport? in
            guard snippet.contentType == .text, let text = snippet.textContent else { return nil }
            return SnippetExport(title: snippet.title, text: text)
        }
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
        return try encoder.encode(exported)
    }

    /// Imports snippets exported by `exportSnippets`, skipping duplicates.
    /// Returns the number of snippets added.
    func importSnippets(from data: Data) throws -> Int {
        let imported = try JSONDecoder().decode([SnippetExport].self, from: data)
        var added = 0
        for entry in imported.reversed() {
            let item = ClipboardItem(contentType: .text, textContent: entry.text, sourceAppName: nil, sourceAppBundleID: nil, title: entry.title)
            guard !snippets.contains(where: { $0.hasSameContent(as: item) }) else { continue }
            snippets.insert(item, at: 0)
            added += 1
        }
        if added > 0 { snippetStore.save(snippets) }
        return added
    }

    // MARK: - Private

    private func purgeExpiredItems() {
        let cutoff = Date().addingTimeInterval(-AppSettings.shared.retentionPeriod.timeInterval)
        removeItems { !$0.isPinned && $0.timestamp < cutoff }
        enforceHistoryLimit()
    }

    private func removeItems(where shouldRemove: (ClipboardItem) -> Bool) {
        let removed = items.filter(shouldRemove)
        guard !removed.isEmpty else { return }
        deleteImageFiles(for: removed)
        items.removeAll(where: shouldRemove)
        store.save(items)
    }

    /// Drops the oldest unpinned items beyond the configured limit.
    private func enforceHistoryLimit() {
        let limit = AppSettings.shared.maxHistoryItems
        let unpinned = items.filter { !$0.isPinned }
        guard unpinned.count > limit else { return }
        let excess = Set(unpinned[limit...].map(\.id))
        removeItems { excess.contains($0.id) }
    }

    private func checkClipboard() {
        // Periodic retention purge and pause expiry (every 60s / each tick)
        if Date().timeIntervalSince(lastPurgeCheck) > 60 {
            purgeExpiredItems()
            lastPurgeCheck = Date()
        }
        if let pausedUntil, pausedUntil <= Date() {
            self.pausedUntil = nil
        }

        let pasteboard = NSPasteboard.general
        let currentCount = pasteboard.changeCount

        guard currentCount != lastChangeCount else { return }
        lastChangeCount = currentCount

        if ignoreNextChange {
            ignoreNextChange = false
            return
        }

        if pausedUntil != nil { return }
        if isSkippingNextCopy {
            isSkippingNextCopy = false
            return
        }

        // Skip concealed, transient, or auto-generated clipboard data
        let pasteboardTypes = pasteboard.types ?? []
        if Self.sensitiveTypes.contains(where: { pasteboardTypes.contains($0) }) {
            return
        }

        let sourceApp = NSWorkspace.shared.frontmostApplication

        // Skip ignored apps
        if let bundleID = sourceApp?.bundleIdentifier,
           AppSettings.shared.ignoredAppBundleIDs.contains(bundleID) {
            return
        }

        let now = Date()
        let timeSinceLastChange = now.timeIntervalSince(lastClipboardChangeTime)
        lastClipboardChangeTime = now

        if pasteboardTypes.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            record(ClipboardItem.files(urls, sourceApp: sourceApp))
        } else if Self.prefersImage(types: pasteboardTypes),
                  let imageData = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) {
            captureImage(imageData, sourceApp: sourceApp)
        } else if let string = pasteboard.string(forType: .string), !string.isEmpty {
            captureText(string, from: pasteboard, sourceApp: sourceApp, timeSinceLastChange: timeSinceLastChange)
        }
    }

    /// Apps list pasteboard types in their preferred order. Prefer the image
    /// only when the app offers it ahead of any text, so spreadsheet cells
    /// (text plus a rendered picture) are recorded as text.
    static func prefersImage(types: [NSPasteboard.PasteboardType]) -> Bool {
        guard let imageIndex = types.firstIndex(where: imageTypes.contains) else { return false }
        guard let textIndex = types.firstIndex(where: textTypes.contains) else { return true }
        return imageIndex < textIndex
    }

    private func captureImage(_ imageData: Data, sourceApp: NSRunningApplication?) {
        // Decode + re-encode + write the file off the main thread; the raw
        // pasteboard bytes and source app strings are all we capture here.
        let sourceName = sourceApp?.localizedName
        let sourceBundle = sourceApp?.bundleIdentifier
        imageProcessingQueue.async { [weak self] in
            guard let pngData = Self.pngData(from: imageData),
                  let fileName = ImageStore.shared.write(pngData) else { return }
            let hash = ImageStore.hash(pngData)
            DispatchQueue.main.async {
                let item = ClipboardItem.image(fileName: fileName, hash: hash, sourceAppName: sourceName, sourceAppBundleID: sourceBundle)
                self?.record(item)
            }
        }
    }

    private func captureText(_ string: String, from pasteboard: NSPasteboard, sourceApp: NSRunningApplication?, timeSinceLastChange: TimeInterval) {
        guard string.utf8.count <= Self.maxTextBytes else {
            logger.info("Skipped clipboard text larger than \(Self.maxTextBytes) bytes")
            return
        }

        let isSensitive = sourceApp?.bundleIdentifier.map(AppSettings.sensitiveAppBundleIDs.contains) ?? false

        // Merge mode: append to the most recent item if it came from the same
        // app within the time window. Never merges sensitive or pinned items.
        let settings = AppSettings.shared
        if settings.isMergeEnabled,
           !isSensitive,
           timeSinceLastChange < settings.mergeWindowSeconds,
           let first = items.first, first.contentType == .text, !first.isPinned, !first.isSensitive,
           first.sourceAppBundleID == sourceApp?.bundleIdentifier,
           let existingText = first.textContent, existingText != string {
            items[0].textContent = existingText + "\n" + string
            items[0].rtfData = nil
            items[0].htmlData = nil
            store.save(items)
            return
        }

        func richData(_ type: NSPasteboard.PasteboardType) -> Data? {
            guard !isSensitive, let data = pasteboard.data(forType: type), data.count <= Self.maxRichTextBytes else { return nil }
            return data
        }
        record(ClipboardItem.text(string, rtfData: richData(.rtf), htmlData: richData(.html), sourceApp: sourceApp))
    }

    /// Inserts a newly captured item, or moves an existing identical item to
    /// the top instead of duplicating it.
    private func record(_ item: ClipboardItem) {
        if let index = items.firstIndex(where: { $0.hasSameContent(as: item) }) {
            // The new copy's image file is redundant with the existing one.
            if item.imageFileName != items[index].imageFileName {
                deleteImageFile(for: item)
            }
            moveToFront(at: index)
            store.save(items)
            return
        }
        items.insert(item, at: 0)
        enforceHistoryLimit()
        store.save(items)
    }

    private func moveToFront(at index: Int) {
        var item = items.remove(at: index)
        item.timestamp = Date()
        items.insert(item, at: 0)
    }

    // MARK: - Image file cleanup

    private func deleteImageFile(for item: ClipboardItem) {
        if item.contentType == .image, let name = item.imageFileName {
            ImageStore.shared.delete(name)
        }
    }

    private func deleteImageFiles(for items: [ClipboardItem]) {
        for item in items {
            deleteImageFile(for: item)
        }
    }

    private nonisolated static func pngData(from raw: Data) -> Data? {
        guard let bitmapRep = NSBitmapImageRep(data: raw) else { return nil }
        return bitmapRep.representation(using: .png, properties: [.compressionFactor: 0.8])
    }
}
